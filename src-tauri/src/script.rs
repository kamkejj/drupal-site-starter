use crate::config::Project;
use crate::steps::{config_sync_line, Action, Step, DDEV_INCLUDE_MARKER, PASSWORD_ENV, SETTINGS_PHP};

pub fn quote(s: &str) -> String {
    let plain = !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || "-_./:=@^,+%".contains(c));
    if plain { s.to_string() } else { format!("'{}'", s.replace('\'', r"'\''")) }
}

fn command(program: &str, args: &[String]) -> String {
    std::iter::once(program.to_string())
        .chain(args.iter().map(|a| quote(a)))
        .collect::<Vec<_>>()
        .join(" ")
}

fn render_action(action: &Action, p: &Project) -> String {
    match action {
        Action::CreateProjectDir => {
            format!("mkdir -p {name}\ncd {name}", name = quote(&p.name))
        }
        Action::Ddev { args, stdin_secret: false } => command("ddev", args),
        Action::Ddev { args, stdin_secret: true } => {
            format!("printf '%s\\n' \"${PASSWORD_ENV}\" | {}", command("ddev", args))
        }
        Action::Git { args } => command("git", args),
        Action::GitClone { url } => {
            format!("git clone -- {} {name}\ncd {name}", quote(url), name = quote(&p.name))
        }
        Action::Mkdir { path } => format!("mkdir -p {}", quote(path)),
        Action::WriteFile { path, contents } if contents.is_empty() => {
            format!("mkdir -p {} && touch {}", quote(&parent(path)), quote(path))
        }
        Action::WriteFile { path, contents } => {
            let dir = parent(path);
            let mkdir = if dir == "." { String::new() } else { format!("mkdir -p {}\n", quote(&dir)) };
            format!("{mkdir}cat > {} <<'SITE_STARTER_EOF'\n{}SITE_STARTER_EOF", quote(path), contents)
        }
        Action::AppendFile { path, text } => {
            format!("cat >> {} <<'SITE_STARTER_EOF'\n{}SITE_STARTER_EOF", quote(path), text)
        }
        Action::SetConfigSyncDir { dir } => {
            let line = config_sync_line(dir);
            format!(
                "grep -qF {} {SETTINGS_PHP} || \\\n  \
                 perl -0pi -e 's|^(\\Q{DDEV_INCLUDE_MARKER}\\E)|{}\\n\\n$1|m' {SETTINGS_PHP}",
                quote(&line),
                line.replace('$', "\\$").replace('\'', "'\\''"),
            )
        }
    }
}

fn parent(path: &str) -> String {
    match path.rsplit_once('/') {
        Some((dir, _)) => dir.to_string(),
        None => ".".to_string(),
    }
}

pub fn render(p: &Project, steps: &[Step]) -> String {
    let mut out = format!(
        "#!/usr/bin/env bash\n\
         # Creates the DDEV Drupal project \"{name}\". Generated by Drupal Site Starter.\n\
         set -euo pipefail\n\
         export DDEV_NONINTERACTIVE=true\n\n\
         if [ -z \"${{{PASSWORD_ENV}:-}}\" ]; then\n  \
           read -rsp 'Drupal admin password: ' {PASSWORD_ENV}; echo\n\
         fi\n\n\
         cd {parent}\n",
        name = p.name,
        parent = quote(&p.dir.parent().expect("project dir has a parent").display().to_string()),
    );
    for s in steps {
        out.push_str(&format!("\n# {}\n{}\n", s.title, render_action(&s.action, p)));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quote_leaves_simple_words_and_escapes_the_rest() {
        assert_eq!(quote("--php-version=8.3"), "--php-version=8.3");
        assert_eq!(quote("My Site"), "'My Site'");
        assert_eq!(quote("it's"), r"'it'\''s'");
        assert_eq!(quote("$(rm -rf /)"), "'$(rm -rf /)'");
        assert_eq!(quote(""), "''");
    }
}
